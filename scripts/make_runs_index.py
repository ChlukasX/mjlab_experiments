"""Write docs/runs_index.md: one row per training run in logs/rsl_rl.

    uv run python scripts/make_runs_index.py            # write the file
    uv run python scripts/make_runs_index.py --check    # exit 1 when the file is out of date

Sources (all untracked, local to the machine that trained):
- `logs/rsl_rl/<log group>/<run>/git/mjlab_experiments.diff`: the commit and the state of the tree at launch.
- `logs/rsl_rl/<log group>/<run>/model_N.pt`: the checkpoint.
- `wandb/run-*/files/wandb-metadata.json`: the exact command line (`args`) and the wandb run ID.

A wandb run belongs to a run directory when its task writes into the log group (or the task is
unknown, as for runs from before the package rename), its start time is within 180 s of the run
directory's timestamp. A wandb run whose `--agent.run-name` differs from the run's name (a directory
renamed by hand) matches only within 60 s. Directories named `init-from-*` are copies, not launches.
The index is derived data. Do not edit it by hand. Regenerate it after new runs.
"""

import argparse
import importlib.util
import json
import re
import shlex
import sys
from datetime import datetime
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
LOGS = REPO / "logs" / "rsl_rl"
WANDB = REPO / "wandb"
OUT = REPO / "docs" / "runs_index.md"
MAX_SECONDS = 180

HEADER = """# Runs index

Generated by `scripts/make_runs_index.py` from `logs/rsl_rl/` and the local `wandb/` metadata. Do not edit by hand.
One row per training run. `logs/` and `wandb/` are not in git; the wandb cloud holds the same runs and checkpoints.

- **Run ID**: the name part of the run directory (`—` when the run had no name).
- **Commit / Tree**: the git commit at launch, and `clean` or `dirty` (uncommitted changes; the diff is in the run's `git/` directory). `—`: no git record.
- **wandb**: the wandb run ID. `—`: no matching local wandb directory.
- **Loadable**: `no` when the checkpoint does not fit the current task (history only), else `yes`. Checked by `scripts/check_tasks.py --checkpoints`.
- **Launch arguments**: the arguments after `uv run train`, from the wandb metadata. Recovered; the original launch scripts are lost.

"""


def load_check_tasks():
    spec = importlib.util.spec_from_file_location("check_tasks", REPO / "scripts" / "check_tasks.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def parse_run_dir(name):
    m = re.match(r"(\d{4}-\d\d-\d\d_\d\d-\d\d-\d\d)(?:_(.+))?$", name)
    stamp = datetime.strptime(m.group(1), "%Y-%m-%d_%H-%M-%S")
    return stamp, m.group(2)


def read_git(run):
    path = run / "git" / "mjlab_experiments.diff"
    if not path.exists():
        return "—", "—"
    text = path.read_text(errors="replace")
    m = re.search(r"--- git commit ---\n([0-9a-f]{7,40})", text)
    commit = m.group(1)[:10] if m else "—"
    status = re.search(r"--- git status ---\n(.*?)\n--- git diff ---", text, re.DOTALL)
    tree = "—"
    if status is not None:
        tree = "clean" if "nothing to commit" in status.group(1) else "dirty"
    return commit, tree


def read_wandb(task_group):
    """All local wandb runs as dicts: id, start (local time), task, run name, args."""
    runs = []
    for meta in sorted(WANDB.glob("run-*/files/wandb-metadata.json")):
        m = re.match(r"run-(\d{8}_\d{6})-(\w+)$", meta.parent.parent.name)
        if not m:
            continue
        args = json.loads(meta.read_text()).get("args") or []
        name = args[args.index("--agent.run-name") + 1] if "--agent.run-name" in args else None
        runs.append(
            {
                "id": m.group(2),
                "start": datetime.strptime(m.group(1), "%Y%m%d_%H%M%S"),
                "task": args[0] if args else None,
                "name": name,
                "args": args,
                "group": task_group.get(args[0]) if args else None,
            }
        )
    return runs


def match_wandb(wandb_runs, group, stamp, name, taken):
    """Nearest wandb run in time. A run directory renamed by hand (the name differs from
    `--agent.run-name`) matches only within 60 s."""
    best = None
    for w in wandb_runs:
        if w["id"] in taken:
            continue
        if w["group"] is not None and w["group"] != group:
            continue
        dt = abs((w["start"] - stamp).total_seconds())
        renamed = bool(name and w["name"] and w["name"] != name)
        if dt > (60 if renamed else MAX_SECONDS):
            continue
        key = (renamed, dt)
        if best is None or key < best[0]:
            best = (key, w)
    return best[1] if best else None


def esc(text):
    return text.replace("|", "\\|")


def build():
    ct = load_check_tasks()
    from mjlab.tasks.registry import load_rl_cfg

    task_group = {t: load_rl_cfg(t).experiment_name for t in ct.piplus_tasks()}
    wandb_runs = read_wandb(task_group)
    taken = set()
    lines = [HEADER.rstrip("\n"), ""]
    lines += [
        "| Log group | Run directory | Run ID | Commit | Tree | wandb | Checkpoint | Loadable | Launch arguments |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    n_runs = n_wandb = n_git = 0
    for group_dir in sorted(p for p in LOGS.iterdir() if p.is_dir()):
        for run in sorted(p for p in group_dir.iterdir() if p.is_dir()):
            stamp, name = parse_run_dir(run.name)
            commit, tree = read_git(run)
            w = match_wandb(wandb_runs, group_dir.name, stamp, name, taken)
            if w:
                taken.add(w["id"])
            ckpts = sorted(run.glob("model_*.pt"), key=lambda p: int(p.stem.split("_")[1]))
            ckpt = ckpts[-1].name if ckpts else "—"
            loadable = "no" if (group_dir.name, run.name) in ct.KNOWN_UNLOADABLE else "yes"
            args = shlex.join(w["args"]) if w else "—"
            n_runs += 1
            n_wandb += bool(w)
            n_git += commit != "—"
            lines.append(
                f"| `{group_dir.name}` | `{run.name}` | {f'`{name}`' if name else '—'} | "
                f"{f'`{commit}`' if commit != '—' else '—'} | {tree} | {f'`{w['id']}`' if w else '—'} | "
                f"{f'`{ckpt}`' if ckpt != '—' else '—'} | {loadable} | {f'`{esc(args)}`' if w else '—'} |"
            )
    unmatched = [w for w in wandb_runs if w["id"] not in taken]
    summary = (
        f"{n_runs} runs. {n_git} with a git record, {n_wandb} with recovered launch arguments. "
        f"{len(unmatched)} of {len(wandb_runs)} local wandb directories match no run directory "
        "(for example runs whose log directory was deleted)."
    )
    lines += ["", summary, ""]
    return "\n".join(lines), (n_runs, n_git, n_wandb, len(wandb_runs), len(unmatched))


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when docs/runs_index.md is out of date")
    args = parser.parse_args()
    if not LOGS.exists():
        sys.exit(f"no {LOGS}: this machine has no training logs")
    text, stats = build()
    print("runs {}, with git {}, with wandb args {}, wandb dirs {}, unmatched wandb dirs {}".format(*stats))
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print("docs/runs_index.md is out of date: run scripts/make_runs_index.py")
            return 1
        return 0
    OUT.write_text(text)
    print(f"written: {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
