"""Export the ball-mount policy for the Bit-Bots robot code.

Writes `<out>/<name>.onnx` (normalizer included; input [1, 345], output [1, 20]) and
`<out>/<name>.yaml`, a `bitbots_rl_motion` parameter file for `deploy/bitbots/mount_ball_node.py`
with the joint order, home pose, gains, joint ranges and on-ball latch taken from the task.
Checks that onnxruntime reproduces the PyTorch policy.

    uv run --with onnxruntime python scripts/export_mount.py \
        --checkpoint logs/rsl_rl/piplus_ball_mountmin_blindonball/<run>/model_N.pt
"""

import argparse
from dataclasses import asdict
from pathlib import Path

import numpy as np
import onnxruntime as ort
import torch
import yaml

import mjlab_piplus  # noqa: F401  (registers tasks)
from mjlab.envs import ManagerBasedRlEnv
from mjlab.rl import MjlabOnPolicyRunner, RslRlVecEnvWrapper
from mjlab.tasks.registry import load_env_cfg, load_rl_cfg

from mjlab_piplus.tasks.ball_mount.piplus_ball_mountbalance_env_cfg import _joint_limit_clip

parser = argparse.ArgumentParser()
parser.add_argument("--checkpoint", required=True)
parser.add_argument("--task", default="Mjlab-Piplus-Ball-MountMin-BlindOnBall")
parser.add_argument("--out", default="deploy/bitbots")
parser.add_argument("--name", default="mount_ball")
args = parser.parse_args()

cfg = load_env_cfg(args.task, play=True)
cfg.scene.num_envs = 1
env = RslRlVecEnvWrapper(ManagerBasedRlEnv(cfg, device="cpu"))
u = env.unwrapped
runner = MjlabOnPolicyRunner(env, asdict(load_rl_cfg(args.task)), device="cpu")
runner.load(args.checkpoint, load_cfg={"actor": True}, strict=True, map_location="cpu")
out = Path(args.out)
runner.export_policy_to_onnx(str(out), f"{args.name}.onnx")

# onnxruntime against PyTorch on observations seen in the sim.
policy = runner.get_inference_policy(device="cpu")
sess = ort.InferenceSession(str(out / f"{args.name}.onnx"), providers=["CPUExecutionProvider"])
obs = env.get_observations()
err = 0.0
for _ in range(50):
    with torch.no_grad():
        a = policy(obs)
    a_onnx = sess.run(None, {sess.get_inputs()[0].name: obs["actor"].numpy()})[0]
    err = max(err, float(np.abs(a_onnx - a.numpy()).max()))
    obs, *_ = env.step(a)
assert err < 1e-4, f"ONNX differs from PyTorch by {err}"

term = u.action_manager.get_term("joint_pos")
names = list(term.target_names)
mj = u.sim.mj_model
robot = u.scene["robot"]
act = {mj.actuator(f"robot/{n}").trnid[0]: mj.actuator(f"robot/{n}") for n in robot.actuator_names}
jid = {n: mj.joint(f"robot/{n}").id for n in names}
limits = _joint_limit_clip()
ball_term = cfg.observations["actor"].terms["ball_pos"].params
params = {
    "model": f"{args.name}.onnx",
    "joints": {
        "ordered_relevant_joint_names": names,
        "walkready_state": [float(x) for x in term._offset[0].tolist()],
        "kp": [float(act[jid[n]].gainprm[0]) for n in names],
        "kd": [float(-act[jid[n]].biasprm[2]) for n in names],
        "action_scales": [float(x) for x in torch.as_tensor(term._scale).expand(len(names)).tolist()],
        # This MJCF uses the robot's joint convention (as the Bit-Bots mjlab walk policy). Check on the robot.
        "joint_signs": [1.0] * len(names),
        "lower_limits": [limits[n][0] for n in names],
        "upper_limits": [limits[n][1] for n in names],
    },
    "on_ball": {"height": float(ball_term["height_threshold"]), "max_tilt": float(ball_term["max_tilt"])},
    "phase": {"use_phase": False, "control_dt": float(u.step_dt), "gait_frequency": 0.0},
    "providers": ["CPUExecutionProvider"],
}
(out / f"{args.name}.yaml").write_text(
    f"# Generated by scripts/export_mount.py from {args.checkpoint}\n"
    + yaml.safe_dump({"mount_ball_node": {"ros__parameters": params}}, sort_keys=False)
)
print(f"wrote {out / args.name}.onnx and .yaml; max |onnx - torch| = {err:.2e}")
